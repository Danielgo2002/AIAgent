export function buildInstructions(memoryBlock: string, companionMode = false): string {
  return [BASE_INSTRUCTIONS, IDO_MASALA_INSTRUCTIONS, memoryBlock, companionMode ? COMPANION_INSTRUCTIONS : '']
    .filter(Boolean)
    .join('\n\n');
}

